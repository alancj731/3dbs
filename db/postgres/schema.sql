-- AdventureWorksLT (SalesLT) for PostgreSQL 17.
-- Identifiers are unquoted, so Postgres folds them to lower case. That makes
-- `SELECT FirstName FROM SalesLT.Customer` work exactly as written on SQL Server and MySQL.
-- Data is copied from SQL Server by the API's Seeder.

DROP SCHEMA IF EXISTS SalesLT CASCADE;
CREATE SCHEMA SalesLT;

CREATE TABLE SalesLT.ProductCategory (
  ProductCategoryID       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ParentProductCategoryID INT NULL REFERENCES SalesLT.ProductCategory (ProductCategoryID),
  Name                    VARCHAR(50) NOT NULL,
  rowguid                 UUID NOT NULL DEFAULT gen_random_uuid(),
  ModifiedDate            TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT AK_ProductCategory_Name UNIQUE (Name),
  CONSTRAINT AK_ProductCategory_rowguid UNIQUE (rowguid)
);

CREATE TABLE SalesLT.ProductModel (
  ProductModelID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Name           VARCHAR(50) NOT NULL,
  rowguid        UUID NOT NULL DEFAULT gen_random_uuid(),
  ModifiedDate   TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT AK_ProductModel_Name UNIQUE (Name),
  CONSTRAINT AK_ProductModel_rowguid UNIQUE (rowguid)
);

CREATE TABLE SalesLT.ProductDescription (
  ProductDescriptionID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Description          VARCHAR(400) NOT NULL,
  rowguid              UUID NOT NULL DEFAULT gen_random_uuid(),
  ModifiedDate         TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT AK_ProductDescription_rowguid UNIQUE (rowguid)
);

CREATE TABLE SalesLT.ProductModelProductDescription (
  ProductModelID       INT NOT NULL REFERENCES SalesLT.ProductModel (ProductModelID),
  ProductDescriptionID INT NOT NULL REFERENCES SalesLT.ProductDescription (ProductDescriptionID),
  Culture              CHAR(6) NOT NULL,
  rowguid              UUID NOT NULL DEFAULT gen_random_uuid(),
  ModifiedDate         TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (ProductModelID, ProductDescriptionID, Culture),
  CONSTRAINT AK_ProductModelProductDescription_rowguid UNIQUE (rowguid)
);

CREATE TABLE SalesLT.Product (
  ProductID              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Name                   VARCHAR(50) NOT NULL,
  ProductNumber          VARCHAR(25) NOT NULL,
  Color                  VARCHAR(15) NULL,
  StandardCost           NUMERIC(19,4) NOT NULL CONSTRAINT CK_Product_StandardCost CHECK (StandardCost >= 0.00),
  ListPrice              NUMERIC(19,4) NOT NULL CONSTRAINT CK_Product_ListPrice CHECK (ListPrice >= 0.00),
  Size                   VARCHAR(5) NULL,
  Weight                 NUMERIC(8,2) NULL CONSTRAINT CK_Product_Weight CHECK (Weight > 0.00),
  ProductCategoryID      INT NULL REFERENCES SalesLT.ProductCategory (ProductCategoryID),
  ProductModelID         INT NULL REFERENCES SalesLT.ProductModel (ProductModelID),
  SellStartDate          TIMESTAMP(3) NOT NULL,
  SellEndDate            TIMESTAMP(3) NULL,
  DiscontinuedDate       TIMESTAMP(3) NULL,
  ThumbnailPhotoFileName VARCHAR(50) NULL,
  rowguid                UUID NOT NULL DEFAULT gen_random_uuid(),
  ModifiedDate           TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT AK_Product_Name UNIQUE (Name),
  CONSTRAINT AK_Product_ProductNumber UNIQUE (ProductNumber),
  CONSTRAINT AK_Product_rowguid UNIQUE (rowguid),
  CONSTRAINT CK_Product_SellEndDate CHECK (SellEndDate >= SellStartDate OR SellEndDate IS NULL)
);

CREATE TABLE SalesLT.Customer (
  CustomerID   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NameStyle    BOOLEAN NOT NULL DEFAULT FALSE,
  Title        VARCHAR(8) NULL,
  FirstName    VARCHAR(50) NOT NULL,
  MiddleName   VARCHAR(50) NULL,
  LastName     VARCHAR(50) NOT NULL,
  Suffix       VARCHAR(10) NULL,
  CompanyName  VARCHAR(128) NULL,
  SalesPerson  VARCHAR(256) NULL,
  EmailAddress VARCHAR(50) NULL,
  Phone        VARCHAR(25) NULL,
  PasswordHash VARCHAR(128) NOT NULL,
  PasswordSalt VARCHAR(10) NOT NULL,
  rowguid      UUID NOT NULL DEFAULT gen_random_uuid(),
  ModifiedDate TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT AK_Customer_rowguid UNIQUE (rowguid)
);
CREATE INDEX IX_Customer_EmailAddress ON SalesLT.Customer (EmailAddress);

CREATE TABLE SalesLT.Address (
  AddressID     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  AddressLine1  VARCHAR(60) NOT NULL,
  AddressLine2  VARCHAR(60) NULL,
  City          VARCHAR(30) NOT NULL,
  StateProvince VARCHAR(50) NOT NULL,
  CountryRegion VARCHAR(50) NOT NULL,
  PostalCode    VARCHAR(15) NOT NULL,
  rowguid       UUID NOT NULL DEFAULT gen_random_uuid(),
  ModifiedDate  TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT AK_Address_rowguid UNIQUE (rowguid)
);

CREATE TABLE SalesLT.CustomerAddress (
  CustomerID   INT NOT NULL REFERENCES SalesLT.Customer (CustomerID),
  AddressID    INT NOT NULL REFERENCES SalesLT.Address (AddressID),
  AddressType  VARCHAR(50) NOT NULL,
  rowguid      UUID NOT NULL DEFAULT gen_random_uuid(),
  ModifiedDate TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (CustomerID, AddressID),
  CONSTRAINT AK_CustomerAddress_rowguid UNIQUE (rowguid)
);

CREATE TABLE SalesLT.SalesOrderHeader (
  SalesOrderID           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  RevisionNumber         SMALLINT NOT NULL DEFAULT 0,
  OrderDate              TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  DueDate                TIMESTAMP(3) NOT NULL,
  ShipDate               TIMESTAMP(3) NULL,
  Status                 SMALLINT NOT NULL DEFAULT 1 CONSTRAINT CK_SalesOrderHeader_Status CHECK (Status BETWEEN 0 AND 8),
  OnlineOrderFlag        BOOLEAN NOT NULL DEFAULT TRUE,
  -- Computed on SQL Server; stored here and filled in by the seeder.
  SalesOrderNumber       VARCHAR(25) NULL,
  PurchaseOrderNumber    VARCHAR(25) NULL,
  AccountNumber          VARCHAR(15) NULL,
  CustomerID             INT NOT NULL REFERENCES SalesLT.Customer (CustomerID),
  ShipToAddressID        INT NULL REFERENCES SalesLT.Address (AddressID),
  BillToAddressID        INT NULL REFERENCES SalesLT.Address (AddressID),
  ShipMethod             VARCHAR(50) NOT NULL,
  CreditCardApprovalCode VARCHAR(15) NULL,
  SubTotal               NUMERIC(19,4) NOT NULL DEFAULT 0.00 CONSTRAINT CK_SalesOrderHeader_SubTotal CHECK (SubTotal >= 0.00),
  TaxAmt                 NUMERIC(19,4) NOT NULL DEFAULT 0.00 CONSTRAINT CK_SalesOrderHeader_TaxAmt CHECK (TaxAmt >= 0.00),
  Freight                NUMERIC(19,4) NOT NULL DEFAULT 0.00 CONSTRAINT CK_SalesOrderHeader_Freight CHECK (Freight >= 0.00),
  TotalDue               NUMERIC(19,4) GENERATED ALWAYS AS (COALESCE(SubTotal + TaxAmt + Freight, 0)) STORED,
  Comment                TEXT NULL,
  rowguid                UUID NOT NULL DEFAULT gen_random_uuid(),
  ModifiedDate           TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT AK_SalesOrderHeader_rowguid UNIQUE (rowguid),
  CONSTRAINT AK_SalesOrderHeader_SalesOrderNumber UNIQUE (SalesOrderNumber),
  CONSTRAINT CK_SalesOrderHeader_DueDate CHECK (DueDate >= OrderDate),
  CONSTRAINT CK_SalesOrderHeader_ShipDate CHECK (ShipDate >= OrderDate OR ShipDate IS NULL)
);

CREATE TABLE SalesLT.SalesOrderDetail (
  SalesOrderID       INT NOT NULL REFERENCES SalesLT.SalesOrderHeader (SalesOrderID) ON DELETE CASCADE,
  SalesOrderDetailID INT GENERATED BY DEFAULT AS IDENTITY,
  OrderQty           SMALLINT NOT NULL CONSTRAINT CK_SalesOrderDetail_OrderQty CHECK (OrderQty > 0),
  ProductID          INT NOT NULL REFERENCES SalesLT.Product (ProductID),
  UnitPrice          NUMERIC(19,4) NOT NULL CONSTRAINT CK_SalesOrderDetail_UnitPrice CHECK (UnitPrice >= 0.00),
  UnitPriceDiscount  NUMERIC(19,4) NOT NULL DEFAULT 0.0 CONSTRAINT CK_SalesOrderDetail_UnitPriceDiscount CHECK (UnitPriceDiscount >= 0.00),
  LineTotal          NUMERIC(38,6) GENERATED ALWAYS AS (COALESCE(UnitPrice * (1.0 - UnitPriceDiscount) * OrderQty, 0.0)) STORED,
  rowguid            UUID NOT NULL DEFAULT gen_random_uuid(),
  ModifiedDate       TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (SalesOrderID, SalesOrderDetailID),
  CONSTRAINT AK_SalesOrderDetail_rowguid UNIQUE (rowguid)
);

-- Restricted login used for running practice SQL: data access only, no DDL.
DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'practice') THEN
    CREATE ROLE practice LOGIN PASSWORD '__PRACTICE_PASSWORD__';
  END IF;
END $$;
GRANT USAGE ON SCHEMA SalesLT TO practice;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA SalesLT TO practice;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA SalesLT TO practice;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
-- Let practice SQL use unqualified table names (Customer instead of SalesLT.Customer).
ALTER ROLE practice SET search_path = saleslt, public;
